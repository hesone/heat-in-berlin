#!/usr/bin/env python3
"""Write web/test/fixtures/parity.json: polygons + the backend's analyse() results + the buildings
needed, so the frontend's static-mode analysis can be tested against the Python implementation."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from shapely.geometry import box, mapping, shape  # noqa: E402

from waerme.analysis import BuildingIndex, analyse  # noqa: E402

POLYGONS = {
    "block_small": box(13.300, 52.505, 13.304, 52.508),
    "block_large": box(13.300, 52.505, 13.315, 52.515),
    "triangle": shape(
        {"type": "Polygon", "coordinates": [[[13.29, 52.51], [13.31, 52.51], [13.30, 52.52], [13.29, 52.51]]]}
    ),
}

feats = json.loads((ROOT / "data" / "derived" / "buildings.geojson").read_text())["features"]
index = BuildingIndex.from_features(feats)
env = box(*shape({"type": "GeometryCollection", "geometries": [mapping(p) for p in POLYGONS.values()]}).bounds)
subset = [
    f
    for f in feats
    if env.contains(shape({"type": "Point", "coordinates": [f["properties"]["cx"], f["properties"]["cy"]]}))
]
out = {
    "note": "Generated by backend/scripts/make_parity_fixture.py from data/derived/buildings.geojson (ODbL).",
    # geometry is not needed: the analysis only uses centroids (cx, cy) and numeric properties
    "buildings": [{"type": "Feature", "id": f["id"], "geometry": None, "properties": f["properties"]} for f in subset],
    "cases": [{"name": k, "polygon": mapping(p), "expected": analyse(p, index)} for k, p in POLYGONS.items()],
}
dest = ROOT / "web" / "test" / "fixtures" / "parity.json"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(json.dumps(out, separators=(",", ":")))
print(f"{dest.relative_to(ROOT)}: {len(subset)} buildings, {len(out['cases'])} cases")
